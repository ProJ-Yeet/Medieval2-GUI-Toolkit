"""Write unittransfer/scriptwords.py: every label and help text of the Module
builder and the add-ons as a literal catalogue call (96e1).

    python dev/checks/scriptwords_gen.py

The builder's vocabulary (scriptbuilder, scriptaddons) is the Pfadfinder-Adam
campaign editor's, kept close to the original so later versions can be taken
again, and it carries its words inline. The catalogue checker reads only
literal ``_i18n.msg("id", "English")`` calls, so this writes one per word,
keyed by what it labels; :func:`scriptwords.word` hands the page the catalogue
message, or the English when the vocabulary has grown since. Run it again
after a newer version of the editor's files is taken.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from unittransfer import scriptaddons as AD, scriptbuilder as SB  # noqa: E402

FIELD = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")


def ident(kind, key):
    slug = re.sub(r"[^a-z0-9]+", "_", f"{kind}_{key}".lower()).strip("_")[:48]
    return f"eng.scriptwords.{slug}_{hashlib.md5(f'{kind}|{key}'.encode()).hexdigest()[:4]}"


rows = []


def add(kind, key, text):
    if text:
        rows.append((kind, key, text))


for e in SB.EVENTS:
    add("event", e.key, e.label)
    add("event_help", e.key, e.help)
for group, kind in ((SB.CONDITIONS, "cond"), (SB.ACTIONS, "act")):
    for p in group:
        add(kind, p.key, p.label)
        add(kind + "_help", p.key, p.help)
        for n, _k, lab, _d in p.fields:
            add("field", f"{p.key}.{n}", lab)
for kind, pairs in (("who", SB.WHO_IS), ("to", SB.TO), ("op", SB.TURN_OPS), ("stance", SB.STANCES),
                    ("match", SB.MATCH), ("each", SB.EACH), ("each_of", SB.EACH_OF)):
    for k, v in pairs:
        add(kind, k, v)
for r in SB.EXAMPLES:
    add("example", r["title"], r["title"])
for a in AD.ADDONS:
    add("addon", a.key, a.title)
    add("addon_help", a.key, a.summary)
    for s in a.settings:
        add("setting", f"{a.key}.{s.var}", s.label)
        add("setting_help", f"{a.key}.{s.var}", s.help)
        for v, lab in s.choices:
            add("choice", f"{a.key}.{s.var}.{v}", lab)

seen = set()
lines = ['"""Generated by dev/checks/scriptwords_gen.py - do not edit by hand.',
         "",
         "Every label and help text of the Module builder and the add-ons as a literal catalogue",
         'call, so the page reads them in its own language (96e1)."""',
         "from . import i18n as _i18n", "", "", "def _table():", "    return {"]
for kind, key, text in rows:
    if (kind, key) in seen:
        continue
    seen.add((kind, key))
    names = sorted(set(FIELD.findall(text)))
    params = "".join(f", {n}={json.dumps('{' + n + '}')}" for n in names)
    lines.append(f"        ({json.dumps(kind)}, {json.dumps(key, ensure_ascii=False)}): "
                 f"lambda: _i18n.msg({json.dumps(ident(kind, key))}, {json.dumps(text, ensure_ascii=False)}{params}),")
lines += ["    }", "", "", "_TABLE = None", "", "",
          "def word(kind, key, default):",
          '    """The catalogue message for one word of the builder, else ``default``."""',
          "    global _TABLE",
          "    if _TABLE is None:",
          "        _TABLE = _table()",
          "    f = _TABLE.get((kind, key))",
          "    return f() if f else default", ""]
(ROOT / "unittransfer" / "scriptwords.py").write_text("\n".join(lines), encoding="utf-8")
print(len(seen), "words")
