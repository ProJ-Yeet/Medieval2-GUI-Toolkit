"""The query engine, the themes and the information maps - Phase 16g, measured.

16f said whether the map would load. This says whether it can be asked
questions about itself, and the three claims under test are the ones a filter
engine is usually only asserted to have:

    every filter fires   a map written here has exactly one province that each
                         filter must match, and every filter is checked against
                         the set it has to return - not against "some result"
    an unaskable filter  a vocabulary the mod does not ship turns its filter off
    says which file      WITH THE FILE NAMED, and takes no part in a query, so
                         it can neither empty an `all` nor widen an `any`
    what is drawn is     the region-to-colour table the browser paints and the
    what is written      TGA Python writes come out of one Colouring, and the
                         exported file round-trips byte for byte

The stock game is the measurement for the second claim, exactly as it was in
16f: its ``data/`` is packed, ``descr_sm_factions.txt`` is not on disk, and a
reader that does not check offers a culture filter with nothing in it and a
culture map that is uniformly blank.

Five parts, the last two of which need a game install:

    1  the three small files nothing else in the toolkit reads
    2  a map written here: every filter, and the exact set it must return
    3  colours, ramps, borders and the TGA round trip
    4  every real map: the vocabulary, the timings, and what it finds
    5  the four routes over real HTTP

    python -m tests.test_mapquery
"""
